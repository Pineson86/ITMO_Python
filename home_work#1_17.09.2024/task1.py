x = int(input('Введите первое число и нажимите Enter: '))
y = int(input('Введите второе число и нажмите Enter: '))
print(f'Сумма: {x + y}')
print(f'Разность: {x - y}')
print(f'Произведение: {x * y}')
print(f'Отношение: {x / y}')
print(f'Остаток деления: {x % y}')
print(f'{x} в степени {y} равно {x ** y}')